export function normalizeLocale(locale) {
  return LOCALES.includes(locale) ? locale : "zh_cn";
}

export function localeTag(locale) {
  return LANGUAGE_OPTIONS.find((option) => option.id === normalizeLocale(locale))?.htmlLang ?? "zh-CN";
}

export function text(locale, key, ...args) {
  const value = TEXT[normalizeLocale(locale)]?.[key] ?? TEXT.zh_cn[key] ?? key;
  return typeof value === "function" ? value(...args) : value;
}

export function localizedName(entity, type, locale, localization) {
  const normalizedLocale = normalizeLocale(locale);
  if (normalizedLocale === "en") return entity?.name_en ?? entity?.name_zh_cn ?? "";
  if (normalizedLocale === "zh_cn") return entity?.name_zh_cn ?? entity?.name_en ?? "";
  const id = entity?.student_id ?? entity?.id ?? entity?.node_id;
  return localization?.[`${type}s`]?.[String(id)] ?? entity?.name_ja ?? entity?.name_en ?? entity?.name_zh_cn ?? "";
}

export function localizedReactionLabel(grade, locale) {
  const labels = {
    zh_cn: { 1: "小", 2: "中", 3: "大", 4: "特大" },
    en: { 1: "Small", 2: "Medium", 3: "Large", 4: "Huge" },
    ja: { 1: "小", 2: "中", 3: "大", 4: "特大" },
  };
  return labels[normalizeLocale(locale)][grade] ?? "";
}

export function readStoredLocale(storage) {
  try {
    return normalizeLocale(storage?.getItem("schale-dashboard-locale"));
  } catch {
    return "zh_cn";
  }
}

export function writeStoredLocale(storage, locale) {
  const normalizedLocale = normalizeLocale(locale);
  try {
    storage?.setItem("schale-dashboard-locale", normalizedLocale);
  } catch {
    // Private browsing or blocked storage should not prevent language switching.
  }
  return normalizedLocale;
}
